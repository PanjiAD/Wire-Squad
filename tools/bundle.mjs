// Builds the standalone index.html from engine/, data/ and app/.
//
//   node tools/bundle.mjs
//
// The engine modules are plain ESM with single-line named imports and one
// default JSON import in data.js. This bundler strips imports/exports and
// concatenates the modules in dependency order, then validates the result:
//  - every imported binding must be declared somewhere in the bundle
//  - no top-level name may be declared twice
//  - the bundle is imported in Node and a small game is played
//
// No dependencies, no network.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');

const MODULES = [
  'engine/constants.js',
  'engine/rng.js',
  'engine/data.js',
  'engine/helpers.js',
  'engine/setup.js',
  'engine/actions.js',
  'engine/view.js',
  'net/config.js',
  'net/client.js',
  'app/strings.en.js',
  'app/help-art.js',
  'app/app.js',
];

const JSON_IMPORTS = {
  missionsFile: 'data/missions.json',
  equipmentFile: 'data/equipment.json',
  charactersFile: 'data/characters.json',
};

const IMPORT_DEFAULT_JSON = /^import\s+([A-Za-z_$][\w$]*)\s+from\s+'\.\.\/data\/([A-Za-z0-9_.-]+\.json)'\s+with\s*\{\s*type:\s*'json'\s*\};[ \t]*$/gm;
const IMPORT_NAMED = /^import\s*\{([\s\S]*?)\}\s*from\s*'([^']+)';[ \t]*$/gm;
const IMPORT_LEFT = /^import\b/m;
const EXPORT_DECL = /^export\s+((?:async\s+)?(function|const|let|class)\s)/gm;
const DECLARED = /^(?:export\s+)?(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

const declared = new Map();
const imported = [];
const parts = [];

function fail(message) {
  console.error(`bundle failed: ${message}`);
  process.exit(1);
}

function jsonOf(relative) {
  const full = path.join(root, relative);
  if (!fs.existsSync(full)) fail(`missing data file ${relative}`);
  return fs.readFileSync(full, 'utf8').trim();
}

for (const relative of MODULES) {
  const full = path.join(root, relative);
  if (!fs.existsSync(full)) fail(`missing module ${relative}`);
  let code = fs.readFileSync(full, 'utf8');

  // 1. Replace JSON default imports with the parsed document as a literal.
  code = code.replace(IMPORT_DEFAULT_JSON, (match, name, file) => {
    const known = JSON_IMPORTS[name];
    if (!known) fail(`unexpected JSON import ${name} in ${relative}`);
    if (path.basename(known) !== file) fail(`JSON import name/file mismatch for ${name}`);
    imported.push({ name, from: relative });
    return `const ${name} = ${jsonOf(known)};`;
  });

  // 2. Record and remove named imports (they are resolved by concatenation).
  code = code.replace(IMPORT_NAMED, (match, body, from) => {
    for (const piece of body.split(',')) {
      const text = piece.trim();
      if (!text) continue;
      const [importedName, localName] = text.split(/\s+as\s+/).map((part) => part.trim());
      imported.push({ name: localName || importedName, from: relative, source: from });
    }
    return '';
  });

  if (IMPORT_LEFT.test(code)) {
    fail(`unhandled import statement in ${relative}`);
  }

  // 3. Drop the `export` keyword; declarations stay global in the bundle.
  code = code.replace(EXPORT_DECL, '$1 ');

  for (const match of code.matchAll(DECLARED)) {
    const name = match[1];
    if (declared.has(name)) {
      fail(`duplicate top-level name "${name}" in ${relative} and ${declared.get(name)}`);
    }
    declared.set(name, relative);
  }

  parts.push(`// ---- ${relative} ----\n${code.trim()}`);
}

for (const entry of imported) {
  if (!declared.has(entry.name)) {
    fail(`import "${entry.name}" in ${entry.from} is not declared in the bundle`);
  }
}

const styles = fs.readFileSync(path.join(root, 'app', 'styles.css'), 'utf8');
const template = fs.readFileSync(path.join(root, 'app', 'index.template.html'), 'utf8');

const script = [
  '/* Wire Squad local demo - generated by tools/bundle.mjs. Do not edit.',
  '   Edit engine/, data/ or app/ and rebuild. */',
  '(function () {',
  "'use strict';",
  '',
  ...parts,
  '',
  'globalThis.WS = { newGame, applyAction, legalActions, publicView, IllegalAction,',
  '  MISSIONS, EQUIPMENT_CARDS, CHARACTERS, DIAL, INFO, createRng };',
  '})();',
  '',
].join('\n');

const html = template
  .split('__STYLES__').join(styles.trim())
  .split('__SCRIPT__').join(script.trim());

fs.mkdirSync(path.join(root, 'build'), { recursive: true });
fs.writeFileSync(path.join(root, 'build', 'bundle.js'), script, 'utf8');
fs.writeFileSync(path.join(root, 'index.html'), html, 'utf8');

// ---------------------------------------------------------------------------
// Validate: execute the bundle in Node and play a short scripted game.

const url = `${pathToFileURL(path.join(root, 'build', 'bundle.js')).href}?v=${Date.now()}`;
await import(url);

const WS = globalThis.WS;
if (!WS) fail('bundle did not expose globalThis.WS');

const state = WS.newGame({ missionId: 4, players: 3, seed: 7 });
if (state.phase !== 'setup') fail(`expected setup phase, got ${state.phase}`);
const setupActions = WS.legalActions(state, state.players[state.setupSeat].id);
if (setupActions.length === 0) fail('no setup actions');
let next = WS.applyAction(state, setupActions[0]);
if (next.tokens.length !== 1) fail('setup token was not placed');

// Drive the game with the engine's own legal actions until it ends.
let steps = 0;
while (next.phase === 'setup' || next.phase === 'playing') {
  if (steps > 3000) fail('smoke game did not finish');
  const seat = next.phase === 'setup'
    ? next.setupSeat
    : (next.pending ? next.pending.actor : next.activeIndex);
  const actions = WS.legalActions(next, next.players[seat].id, { maxActions: 400 });
  if (actions.length === 0) fail(`smoke game deadlocked at step ${steps}`);
  next = WS.applyAction(next, actions[0]);
  steps += 1;
}
if (next.phase !== 'won' && next.phase !== 'lost') fail('smoke game ended oddly');

const view = WS.publicView(next, next.players[0].id);
const json = JSON.stringify(view);
if (json.includes('"seed"') || json.includes('"rng"')) fail('publicView leaks seed/rng');

console.log(`bundle: ${MODULES.length} modules, index.html ${(html.length / 1024).toFixed(1)} KB`);
console.log(`bundle: smoke game ended "${next.phase}" after ${steps} actions`);
